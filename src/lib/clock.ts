/**
 * Токен доступа выписывает один сервер Supabase, а проверяет другой, и часы у
 * них расходятся на секунду-другую. Только что выданный токен для проверяющего
 * оказывается «выданным в будущем» — допуска на расхождение у проверки нет, и
 * запрос отклоняется. Через секунду тот же самый токен проходит, поэтому
 * лечится это повтором запроса, а не входом заново.
 *
 * Ловится это чаще всего при открытии сайта: там токен обновляется и тут же
 * идёт за данными, то есть ему ноль секунд от роду.
 */

/**
 * Сообщения проверяющего сервера про время токена. Отдельного кода ошибки у них
 * нет — приходит тот же PGRST301, что и у протухшего токена, поэтому различаем
 * по тексту.
 */
const CLOCK_SKEW = /issued at future|not yet valid|used before issued/i

export function isClockSkew(message: string): boolean {
  return CLOCK_SKEW.test(message)
}

/** Паузы перед повторами: токену надо «состариться» на пару секунд. */
export const CLOCK_RETRY_DELAYS = [900, 2100]

export function wait(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms))
}
