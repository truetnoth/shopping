-- Обязательный сайт, открытые справочники города и страны, «Украшения» в моде.
--
-- Разовая правка боевой базы: вставить целиком в SQL Editor проекта → Run.
-- Идемпотентна: все три шага — присваивание, а не сдвиг, повторный запуск
-- ничего не портит. В свежей базе делать ничего не нужно — schema.sql актуален.

-- ---------------------------------------------------------------------------
-- 1. Сайт обязателен
-- ---------------------------------------------------------------------------
-- Форма перестанет сохраняться без ссылки — и при создании, и при
-- редактировании. У брендов, заведённых раньше без сайта, первая же правка
-- потребует его вписать: это осознанное требование редакции.

update public.field_defs set required = true where column_name = 'url';

-- ---------------------------------------------------------------------------
-- 2. Город и страна — открытые справочники
-- ---------------------------------------------------------------------------
-- Тип openselect: варианты берутся из options плюс всё, что уже встречается в
-- данных, и редактор может дописать своё прямо из формы. Остальные справочники
-- остаются закрытыми — открытыми были все, и это приносило опечатки
-- («Нижнее бельё» рядом с «Нижнее белье», см. миграцию 2026-09-02).
--
-- Ограничение приходится пересоздавать: create table if not exists в schema.sql
-- уже созданную таблицу не трогает, новый тип иначе не пройдёт check.

alter table public.field_defs drop constraint if exists field_defs_type_check;
alter table public.field_defs add constraint field_defs_type_check
  check (type in ('text','longtext','url','select','multiselect','number','date','bool','openselect'));

update public.field_defs set type = 'openselect' where column_name in ('city', 'country');

-- ---------------------------------------------------------------------------
-- 3. «Украшения» в категориях моды
-- ---------------------------------------------------------------------------

update public.field_defs
   set options = '{"Одежда","Верхняя одежда","Обувь","Сумки","Аксессуары","Нижнее белье","Украшения"}'
 where table_name = 'brands_fashion'
   and column_name = 'fashion_kind';

